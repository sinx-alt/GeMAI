import re
import uuid
from pathlib import PureWindowsPath

from fastapi import UploadFile

from app.config import settings

# A valid PDF has "%PDF-" near the start. The spec allows it anywhere
# in the first 1024 bytes, so check that window, not just byte 0.
PDF_SIGNATURE = b"%PDF-"
SIGNATURE_WINDOW = 1024
MAX_NAME_LENGTH = 100


class FileValidationError(Exception):
    """Raised when an uploaded file is rejected. Handled in main.py."""

    def __init__(
        self,
        message: str,
        status_code: int = 400,
        error: str = "INVALID_FILE",
    ):
        super().__init__(message)
        self.message = message
        self.status_code = status_code
        self.error = error


def sanitize_filename(filename: str) -> str:
    """
    Returns a safe display name: no folders, no odd characters.
    PureWindowsPath treats both / and \\ as separators, so
    '../../app/main.py.pdf' becomes 'main.py.pdf'.
    """
    name = PureWindowsPath(filename).name
    name = re.sub(r"[^A-Za-z0-9._ -]", "_", name).strip(" .")

    if len(name) > MAX_NAME_LENGTH:
        stem, dot, ext = name.rpartition(".")
        name = stem[: MAX_NAME_LENGTH - len(ext) - 1] + dot + ext

    return name or "document.pdf"


def generate_stored_filename() -> str:
    """Name used on disk. Generated by us, never taken from the user."""
    return f"{uuid.uuid4().hex}.pdf"


def validate_pdf_upload(file: UploadFile) -> str:
    """
    Validates an uploaded PDF (name, extension, size, signature).
    Returns the sanitized original filename for display and storage in the DB.
    Raises FileValidationError if the file is rejected.
    """

    # 1. Filename present
    if not file.filename:
        raise FileValidationError("Filename is missing.", error="MISSING_FILENAME")

    safe_name = sanitize_filename(file.filename)

    # 2. Extension
    if not safe_name.lower().endswith(tuple(settings.allowed_extensions)):
        raise FileValidationError(
            "Only PDF files are allowed.", error="INVALID_EXTENSION"
        )

    # 3. Size (seek to the end, so the file is not read into memory)
    file.file.seek(0, 2)
    file_size = file.file.tell()
    file.file.seek(0)

    if file_size == 0:
        raise FileValidationError("Uploaded file is empty.", error="EMPTY_FILE")

    max_size = settings.max_file_size_mb * 1024 * 1024
    if file_size > max_size:
        raise FileValidationError(
            f"File size exceeds the {settings.max_file_size_mb} MB limit.",
            status_code=413,
            error="FILE_TOO_LARGE",
        )

    # 4. Real PDF signature
    header = file.file.read(SIGNATURE_WINDOW)
    file.file.seek(0)

    if PDF_SIGNATURE not in header:
        raise FileValidationError("Invalid PDF file.", error="INVALID_PDF")

    return safe_name